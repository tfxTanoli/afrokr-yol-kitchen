export const searchIngredientsCatalog = (query: string, categoryFilter?: string): CatalogIngredient[] => {
  const cleanQ = query.trim().toLowerCase();
  
  return INGREDIENTS_CATALOG.filter(item => {
    // Category check
    if (categoryFilter && categoryFilter !== 'all' && item.category !== categoryFilter) {
      return false;
    }

    if (!cleanQ) return true;

    // Name match
    if (item.name.toLowerCase().includes(cleanQ)) return true;

    // Aliases match
    if (item.aliases.some(alias => alias.toLowerCase().includes(cleanQ))) return true;

    // Category match
    if (item.category.toLowerCase().includes(cleanQ)) return true;

    // Tag match
    if (item.tag && item.tag.toLowerCase().includes(cleanQ)) return true;

    return false;
  });
};
